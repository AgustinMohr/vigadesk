CREATE TABLE ms_prd_producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(255),
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    STOCK_ACTUAL DECIMAL(19,3) NOT NULL DEFAULT 0,
    STOCK_MINIMO DECIMAL(19,3) NOT NULL DEFAULT 0,
    precio DECIMAL(38,2) NOT NULL,
    COSTO DECIMAL(19,2),
    UNIDAD_MEDIDA VARCHAR(255),
    DESCUENTO_PROMOCIONAL DECIMAL(38,2) DEFAULT 0,
    categoria VARCHAR(255),
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    FECHA_BORRADO TIMESTAMP,
    ACTUALIZADO_POR VARCHAR(255),
    FECHA_ACTUALIZACION TIMESTAMP,
    VERSION BIGINT,
    PRIMARY KEY (id)
);
