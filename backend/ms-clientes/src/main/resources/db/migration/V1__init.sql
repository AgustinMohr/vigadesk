CREATE TABLE MS_CLI_CLIENTE (
    id INT NOT NULL AUTO_INCREMENT,
    nombre VARCHAR(255) NOT NULL,
    CORREO_ELECTRONICO VARCHAR(255) NOT NULL,
    cuit VARCHAR(255),
    MAXIMO_DESCUBIERTO DECIMAL(38,2),
    HABILITADO BIT(1) NOT NULL DEFAULT b'1',
    FECHA_BORRADO DATETIME(6),
    PRIMARY KEY (id)
);

CREATE TABLE MS_CLI_OBRA (
    id INT NOT NULL AUTO_INCREMENT,
    direccion VARCHAR(255),
    lat FLOAT,
    lng FLOAT,
    ID_CLIENTE INT,
    presupuesto DECIMAL(38,2) NOT NULL,
    estado VARCHAR(255),
    habilitado BIT(1) NOT NULL DEFAULT b'1',
    FECHA_BORRADO DATETIME(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_ms_cli_obra_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES MS_CLI_CLIENTE (id)
);

CREATE TABLE MS_CLI_USUARIO (
    id INT NOT NULL AUTO_INCREMENT,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(255),
    dni VARCHAR(255),
    EMAIL VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    ID_CLIENTE INT,
    ROL VARCHAR(255),
    HABILITADO BIT(1) NOT NULL DEFAULT b'1',
    FECHA_BORRADO DATETIME(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_ms_cli_usuario_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES MS_CLI_CLIENTE (id)
);

CREATE TABLE MS_CLI_PAGO (
    id INT NOT NULL AUTO_INCREMENT,
    ID_CLIENTE INT NOT NULL,
    FECHA DATETIME(6),
    MONTO DECIMAL(19,2) NOT NULL,
    METODO_PAGO VARCHAR(255) NOT NULL,
    OBSERVACION VARCHAR(255),
    REGISTRADO_POR VARCHAR(255),
    HABILITADO BIT(1) NOT NULL DEFAULT b'1',
    FECHA_BORRADO DATETIME(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_ms_cli_pago_cliente FOREIGN KEY (ID_CLIENTE) REFERENCES MS_CLI_CLIENTE (id)
);
